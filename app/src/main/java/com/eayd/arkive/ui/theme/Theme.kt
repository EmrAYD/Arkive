/**
 * Material ColorScheme'de karşılığı olmayan, uygulamaya özel renkler.
 * Kullanım: MaterialTheme.arkiveColors.success
 */
@Immutable
data class ArkiveExtraColors(
    val success: Color,
    val gradientTop: Color,
    val gradientBottom: Color
)

private val LightExtraColors = ArkiveExtraColors(
    success = LightSuccess,
    gradientTop = LightGradientTop,
    gradientBottom = LightGradientBottom
)

private val DarkExtraColors = ArkiveExtraColors(
    success = DarkSuccess,
    gradientTop = DarkGradientTop,
    gradientBottom = DarkGradientBottom
)

val LocalArkiveColors = staticCompositionLocalOf { LightExtraColors }

val MaterialTheme.arkiveColors: ArkiveExtraColors
    @Composable
    @ReadOnlyComposable
    get() = LocalArkiveColors.current

@Composable
fun ArkiveTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Android 12+ duvar kağıdı renkleri marka paletini ezer; bu yüzden varsayılan kapalı.
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }
    val extraColors = if (darkTheme) DarkExtraColors else LightExtraColors

    CompositionLocalProvider(LocalArkiveColors provides extraColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography, // mevcut Type.kt
            content = content
        )
    }
}